#!/usr/bin/env bash
# PAZO P42: isolated GitHub Actions PG17 export/restore regression.
# Fixed placeholder bytes are public test data, NOT a usable signing key.
set -euo pipefail
fail() { echo "P42_BACKUP_LAB_BLOCKED: $1" >&2; exit 1; }
[[ "${GITHUB_ACTIONS:-}" == "true" ]] || fail "NOT_CI"
[[ "${PGPASSWORD:-}" == "f14_synthetic_ci_only" ]] || fail "WRONG_LOGIN"
[[ -z "${DATABASE_URL:-}" && -z "${SUPABASE_DB_URL:-}" &&
   -z "${SUPABASE_ACCESS_TOKEN:-}" && -z "${PAZO_SUPABASE_PROJECT_ID:-}" &&
   -z "${PGSERVICE:-}" ]] || fail "REMOTE_CONFIG_PRESENT"
for cmd in pg_dump pg_restore psql grep mktemp; do
  command -v "$cmd" >/dev/null || fail "MISSING_TOOL"
done
export PGHOST=127.0.0.1 PGPORT=55441 PGUSER=f14_admin PGDATABASE=f14_synthetic
[[ "$(psql -XAtq -v ON_ERROR_STOP=1 -c "SELECT current_database() || '|' || session_user;")" == "f14_synthetic|f14_admin" ]] || fail "WRONG_DATABASE"
[[ "$(pg_dump --version)" == *"PostgreSQL) 17."* ]] || fail "WRONG_CLIENT_VERSION"
# A separate database in the existing disposable PG17 service, not other tests.
psql -X -q -v ON_ERROR_STOP=1 -d postgres -c "CREATE DATABASE f14_p42_backup_source;"
export PGDATABASE=f14_p42_backup_source
scratch="$(mktemp -d)"
trap 'rm -rf -- "$scratch"' EXIT
chmod 700 "$scratch"
[[ "$(psql -XAtq -v ON_ERROR_STOP=1 -c "SELECT to_regclass('supporter_private.p42_activation_signing_keys') IS NULL;")" == "t" ]] || fail "NOT_EMPTY_LAB"
psql -X -q -v ON_ERROR_STOP=1 <<'SQL'
CREATE SCHEMA supporter_private;
CREATE TABLE supporter_private.p42_activation_signing_keys(
 key_id text PRIMARY KEY, key_bytes bytea NOT NULL CHECK(octet_length(key_bytes)>=32),
 enabled boolean NOT NULL DEFAULT false,
 not_before timestamptz NOT NULL, not_after timestamptz
);
ALTER TABLE supporter_private.p42_activation_signing_keys ENABLE ROW LEVEL SECURITY;
ALTER TABLE supporter_private.p42_activation_signing_keys FORCE ROW LEVEL SECURITY;
CREATE TABLE supporter_private.p42_backup_benign_control(id int PRIMARY KEY,label text NOT NULL);
CREATE TABLE supporter_private.p42_backup_parent(
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text UNIQUE NOT NULL
);
CREATE TABLE supporter_private.p42_backup_child(
  id integer PRIMARY KEY, parent_id bigint NOT NULL
    REFERENCES supporter_private.p42_backup_parent(id),
  note text NOT NULL
);
CREATE INDEX p42_backup_child_note_idx ON supporter_private.p42_backup_child(note);
CREATE VIEW supporter_private.p42_backup_parent_count AS
 SELECT count(*)::bigint AS total FROM supporter_private.p42_backup_parent;
CREATE FUNCTION supporter_private.p42_backup_lookup(p_id bigint)
 RETURNS text LANGUAGE sql STABLE
 AS 'SELECT name FROM supporter_private.p42_backup_parent WHERE id=p_id';
GRANT SELECT ON supporter_private.p42_backup_benign_control TO PUBLIC;
INSERT INTO supporter_private.p42_activation_signing_keys(key_id,key_bytes,enabled,not_before,not_after)
VALUES('P42_V1',decode(repeat('a1',32),'hex'),false,
       '2026-10-17T12:00:00Z'::timestamptz,
       '2026-10-18T12:00:00Z'::timestamptz);
INSERT INTO supporter_private.p42_backup_benign_control
VALUES(1,'synthetic-business-data-survives');
INSERT INTO supporter_private.p42_backup_parent(id,name)
VALUES(11,'alpha'),(12,'beta');
INSERT INTO supporter_private.p42_backup_child(id,parent_id,note)
VALUES(50,11,'linked-data-1'),(51,12,'linked-data-2');
SQL


# Exercise server-side parameter placeholders on this disposable database ONLY.
# PREPARE/EXECUTE with PUBLIC fixture bytes; not proof of client wire bind logging
# or a hosted writable role. Transaction ROLLBACK protects backup source state.
bind_status="$(psql -X -Atq -v ON_ERROR_STOP=1 <<'SQL'
BEGIN;
DO $scope$
BEGIN
 IF current_database()<>'f14_p42_backup_source'
    OR session_user<>'f14_admin'
    OR current_setting('server_version_num')::int NOT BETWEEN 170000 AND 179999
    OR (SELECT count(*) FROM supporter_private.p42_activation_signing_keys)<>1
 THEN RAISE EXCEPTION 'synthetic PG17 bind lab identity or baseline mismatch'; END IF;
END $scope$;
PREPARE p42_offline_insert(text,bytea,timestamptz,timestamptz) AS
 INSERT INTO supporter_private.p42_activation_signing_keys
 (key_id,key_bytes,enabled,not_before,not_after)
 VALUES($1,$2,false,$3,$4) RETURNING key_id,enabled;
EXECUTE p42_offline_insert('P42_V2',decode(repeat('a7',32),'hex'),
 '2027-01-20T12:00:00Z'::timestamptz,'2027-01-21T12:00:00Z'::timestamptz);
DO $check$
BEGIN
 IF (SELECT count(*) FROM supporter_private.p42_activation_signing_keys)<>2
 OR (SELECT enabled FROM supporter_private.p42_activation_signing_keys WHERE key_id='P42_V2') IS DISTINCT FROM false
 OR (SELECT not_after - not_before FROM supporter_private.p42_activation_signing_keys WHERE key_id='P42_V2')<> interval '24 hours'
 THEN RAISE EXCEPTION 'synthetic parameterized insert gate failed'; END IF;
END $check$;
PREPARE p42_offline_delete(text) AS
 DELETE FROM supporter_private.p42_activation_signing_keys
 WHERE key_id=$1 RETURNING key_id;
EXECUTE p42_offline_delete('P42_V2');
DO $check2$
BEGIN
 IF (SELECT count(*) FROM supporter_private.p42_activation_signing_keys)<>1
 OR (SELECT count(*) FROM supporter_private.p42_activation_signing_keys WHERE key_id='P42_V1')<>1
 THEN RAISE EXCEPTION 'synthetic exact-key deletion gate failed'; END IF;
END $check2$;
ROLLBACK;
SELECT 'P42_PRIVATE_PARAMETERIZED_PG17_ROLLBACK_PASS_ONLY';
SQL
)"
[[ "$(printf '%s\n' "$bind_status" | tail -n 1)" == "P42_PRIVATE_PARAMETERIZED_PG17_ROLLBACK_PASS_ONLY" ]] || fail "SYNTHETIC_PARAMETERIZED_LAB_FAILED"
[[ "$(psql -XAtq -v ON_ERROR_STOP=1 -c 'SELECT count(*) FROM supporter_private.p42_activation_signing_keys;')" == 1 ]] || fail "SYNTHETIC_ROLLBACK_FAILED"
echo "P42_PRIVATE_PARAMETERIZED_PG17_ROLLBACK_PASS_ONLY"

# Control: the original unrestricted pg_dump includes key material.
pg_dump --format=custom --create --file="$scratch/unfiltered.dump"
pg_restore --list "$scratch/unfiltered.dump" > "$scratch/unfiltered.toc"
grep -Eq '[[:space:]]TABLE DATA[[:space:]]supporter_private[[:space:]]p42_activation_signing_keys[[:space:]]' \
  "$scratch/unfiltered.toc" || fail "NEGATIVE_CONTROL_MISSING"

# Exact candidate: exclude only rows of P42 key table; retain table schema.
pg_dump --format=custom --create \
  --exclude-table-data=supporter_private.p42_activation_signing_keys \
  --file="$scratch/filtered.dump"
pg_restore --list "$scratch/filtered.dump" > "$scratch/filtered.toc"
grep -Eq '[[:space:]]TABLE[[:space:]]supporter_private[[:space:]]p42_activation_signing_keys[[:space:]]' \
  "$scratch/filtered.toc" || fail "KEY_SCHEMA_MISSING"
if grep -Eq '[[:space:]]TABLE DATA[[:space:]]supporter_private[[:space:]]p42_activation_signing_keys[[:space:]]' \
  "$scratch/filtered.toc"; then fail "KEY_DATA_EXPOSED"; fi
grep -Eq '[[:space:]]TABLE DATA[[:space:]]supporter_private[[:space:]]p42_backup_benign_control[[:space:]]' \
  "$scratch/filtered.toc" || fail "BENIGN_DATA_MISSING"
grep -Eq '[[:space:]]TABLE DATA[[:space:]]supporter_private[[:space:]]p42_backup_child[[:space:]]' \
  "$scratch/filtered.toc" || fail "RELATIONAL_DATA_MISSING"
grep -Eq '[[:space:]]INDEX[[:space:]]supporter_private[[:space:]]p42_backup_child_note_idx[[:space:]]' \
  "$scratch/filtered.toc" || fail "INDEX_MISSING"
grep -Eq '[[:space:]]VIEW[[:space:]]supporter_private[[:space:]]p42_backup_parent_count[[:space:]]' \
  "$scratch/filtered.toc" || fail "VIEW_MISSING"

# Restore into a DIFFERENT disposable database; never reuse live PAZO.
psql -X -q -v ON_ERROR_STOP=1 -d postgres -c "CREATE DATABASE f14_p42_filtered_restore;"
pg_restore --exit-on-error --no-owner \
  -d f14_p42_filtered_restore "$scratch/filtered.dump" >/dev/null
actual="$(psql -XAtq -v ON_ERROR_STOP=1 -d f14_p42_filtered_restore <<'SQL'
SELECT (SELECT count(*) FROM supporter_private.p42_activation_signing_keys)::text
 || '|' || (SELECT count(*) FROM supporter_private.p42_backup_benign_control)::text
 || '|' || (SELECT label FROM supporter_private.p42_backup_benign_control WHERE id=1)
 || '|' || (SELECT (relrowsecurity AND relforcerowsecurity)::text FROM pg_class
              WHERE oid='supporter_private.p42_activation_signing_keys'::regclass)
 || '|' || (SELECT CASE WHEN EXISTS (
   SELECT 1 FROM information_schema.columns
   WHERE table_schema='supporter_private'
   AND table_name='p42_activation_signing_keys' AND column_name='key_bytes'
 ) THEN 't' ELSE 'f' END)
 || '|' || (SELECT count(*) FROM supporter_private.p42_backup_child)::text
 || '|' || (SELECT count(*) FROM supporter_private.p42_backup_parent_count)::text
 || '|' || (SELECT total FROM supporter_private.p42_backup_parent_count)::text
 || '|' || (SELECT supporter_private.p42_backup_lookup(11))
 || '|' || (SELECT count(*) FROM pg_constraint
              WHERE contype='f'
                AND conrelid='supporter_private.p42_backup_child'::regclass)::text
 || '|' || (SELECT count(*) FROM pg_indexes
              WHERE schemaname='supporter_private'
                AND indexname='p42_backup_child_note_idx')::text
 || '|' || (SELECT CASE WHEN EXISTS (
   SELECT 1 FROM pg_class c CROSS JOIN LATERAL aclexplode(c.relacl) a
   WHERE c.oid='supporter_private.p42_backup_benign_control'::regclass
     AND a.grantee=0 AND a.privilege_type='SELECT'
 ) THEN 't' ELSE 'f' END);
SQL
)"
[[ "$actual" == "0|1|synthetic-business-data-survives|true|t|2|1|2|alpha|1|1|t" ]] || fail "RESTORE_FAILED"
echo "P42_BACKUP_EXCLUSION_PG17_LAB_PASS_ONLY"
echo "P42_HOSTED_SCRIPT_UNCHANGED_NO_PROVISIONING"
