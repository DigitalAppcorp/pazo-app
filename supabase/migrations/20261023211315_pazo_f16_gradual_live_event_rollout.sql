 DELETE FROM supporter_private.gradual_invitation v USING supporter_private.gradual_campaign c WHERE v.campaign_id=c.id AND c.ended_at<statement_timestamp()-interval '90 days';
 -- Financial admissions/ledger remain under original retention and legal holds.
