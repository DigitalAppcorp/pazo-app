CREATE FUNCTION public.pazo_f16_gradual_admin_action(p_actor uuid,p_action text,p_revision bigint,p_request uuid) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE c supporter_private.gradual_campaign%ROWTYPE;prior supporter_private.gradual_audit%ROWTYPE;entry record;release_rev bigint;
BEGIN
 PERFORM supporter_private.gradual_require_service();
 IF p_actor IS NULL OR NOT EXISTS(SELECT 1 FROM admin_private.admin_grants WHERE user_id=p_actor) THEN RAISE EXCEPTION 'Administrator required' USING ERRCODE='42501';END IF;
 IF p_action IS NULL OR p_action NOT IN('start','pause','resume','stop','resolve','public') OR p_request IS NULL OR p_revision IS NULL THEN RETURN jsonb_build_object('code','invalid_request');END IF;
 SELECT * INTO c FROM supporter_private.gradual_campaign WHERE singleton FOR UPDATE;
 SELECT * INTO prior FROM supporter_private.gradual_audit WHERE request_id=p_request;
 IF FOUND THEN RETURN jsonb_build_object('code',CASE WHEN prior.actor_id=p_actor AND prior.action=p_action AND prior.from_revision=p_revision THEN 'already_recorded' ELSE 'request_conflict' END,'revision',c.revision);END IF;
 IF c.revision<>p_revision THEN RETURN jsonb_build_object('code','revision_changed');END IF;
 IF p_action IN('start','resume','public') THEN
  IF NOT c.hosted_gate_verified THEN RETURN jsonb_build_object('code','hosted_gate_required');END IF;
  IF supporter_private.gradual_legacy_open()>0 THEN RETURN jsonb_build_object('code','legacy_intent_requires_reconciliation');END IF;
  IF NOT supporter_private.gradual_health() THEN RETURN jsonb_build_object('code','health_requires_review');END IF;
 END IF;
 IF p_action='start' AND c.started_at IS NOT NULL THEN RETURN jsonb_build_object('code','campaign_already_started');END IF;
 IF p_action='resume' AND (c.started_at IS NULL OR c.lifecycle NOT IN('paused_admin','paused_automatic')) THEN RETURN jsonb_build_object('code','invalid_transition');END IF;
 IF p_action='public' AND (c.stage<>'LIMITED_COMPLETE' OR c.lifecycle<>'active') THEN RETURN jsonb_build_object('code','public_go_not_ready');END IF;
 IF p_action='resolve' THEN
  IF EXISTS(SELECT 1 FROM supporter_private.pazo_paypal_live_event_inbox WHERE processing_state='held')
   OR NOT EXISTS(SELECT 1 FROM supporter_private.pazo_paypal_live_worker_control WHERE singleton AND enabled AND processing_enabled AND last_heartbeat_at>statement_timestamp()-interval '5 minutes' AND last_outcome IN('idle','processed'))
  THEN RETURN jsonb_build_object('code','health_requires_review');END IF;
  UPDATE supporter_private.gradual_incident SET resolved_at=clock_timestamp() WHERE code='financial_review' AND resolved_at IS NULL;
 END IF;
 IF p_action='start' THEN
  -- The legacy intent MUST be terminal/reconciled, not removed by this migration.
  SELECT revision INTO release_rev FROM admin_private.pazo_live_release_control WHERE singleton FOR UPDATE;
  UPDATE admin_private.pazo_live_release_control SET mode='limited' WHERE singleton;
  FOR entry IN SELECT u.id FROM auth.users u WHERE supporter_private.gradual_eligible(u.id)
   AND NOT supporter_private.gradual_verified(u.id) ORDER BY u.created_at,u.id LIMIT 5 LOOP
   INSERT INTO supporter_private.gradual_invitation(owner_id,campaign_id,expires_at) VALUES(entry.id,c.id,clock_timestamp()+interval '72 hours') ON CONFLICT DO NOTHING;
   PERFORM supporter_private.gradual_notice(entry.id,'invitation','invited');
  END LOOP;
 ELSIF p_action='public' THEN
  UPDATE admin_private.pazo_live_release_control SET mode='public' WHERE singleton;
 END IF;
 UPDATE supporter_private.gradual_campaign SET ended_at=CASE WHEN p_action='stop' THEN clock_timestamp() WHEN p_action IN('start','resume') THEN NULL ELSE ended_at END,
 lifecycle=CASE WHEN p_action IN('pause','stop') THEN 'paused_admin' WHEN p_action='resolve' THEN lifecycle ELSE 'active' END,
  started_at=CASE WHEN p_action='start' THEN clock_timestamp() ELSE started_at END,revision=revision+1 WHERE singleton;
 INSERT INTO supporter_private.gradual_audit(request_id,actor_id,action,from_revision,to_revision) VALUES(p_request,p_actor,p_action,c.revision,c.revision+1);
 PERFORM supporter_private.gradual_pump();
 RETURN jsonb_build_object('code','updated','revision',(SELECT revision FROM supporter_private.gradual_campaign WHERE singleton));
END $$;

-- Durable notification claim + conditional delivery/ACK are separate RPCs. The
-- final delivery and version ACK commit together, so unknown responses are safe.
CREATE FUNCTION public.pazo_f16_gradual_notice_claim() RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE o supporter_private.gradual_outbox%ROWTYPE;t uuid:=gen_random_uuid();
BEGIN
 PERFORM supporter_private.gradual_require_service();
 SELECT * INTO o FROM supporter_private.gradual_outbox WHERE delivered_version<version AND next_attempt_at<=statement_timestamp()
 AND (lease_expires_at IS NULL OR lease_expires_at<statement_timestamp()) ORDER BY next_attempt_at,owner_id LIMIT 1 FOR UPDATE SKIP LOCKED;
 IF NOT FOUND THEN RETURN NULL;END IF;
 UPDATE supporter_private.gradual_outbox SET lease_token=t,lease_expires_at=clock_timestamp()+interval '2 minutes',attempts=attempts+1 WHERE campaign_id=o.campaign_id AND owner_id=o.owner_id AND kind=o.kind;
 RETURN jsonb_build_object('campaign',o.campaign_id,'owner',o.owner_id,'kind',o.kind,'version',o.version,'lease',t);
END $$;
