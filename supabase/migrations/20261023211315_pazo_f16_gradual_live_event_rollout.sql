CREATE TABLE supporter_private.gradual_campaign (
 singleton boolean PRIMARY KEY DEFAULT true CHECK(singleton),
 id uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
 lifecycle text NOT NULL DEFAULT 'inactive' CHECK(lifecycle IN('inactive','active','paused_admin','paused_automatic')),
 stage text NOT NULL DEFAULT 'L1_FIRST_REAL' CHECK(stage IN('L1_FIRST_REAL','L2_SMALL','L3_BETA','L4_EXTENDED','LIMITED_COMPLETE')),
 capacity integer NOT NULL DEFAULT 1 CHECK(capacity IN(1,5,20,50)),
 revision bigint NOT NULL DEFAULT 0 CHECK(revision>=0),
 started_at timestamptz, ended_at timestamptz,
 hosted_gate_verified boolean NOT NULL DEFAULT false,
 webhook_ok_at timestamptz,
 reservation_seconds integer NOT NULL DEFAULT 900 CHECK(reservation_seconds BETWEEN 60 AND 3600),
 notification_version text NOT NULL DEFAULT 'review_v1' CHECK(notification_version IN('review_v1','thanks_v2')),
 CHECK(capacity=CASE stage WHEN 'L1_FIRST_REAL' THEN 1 WHEN 'L2_SMALL' THEN 5 WHEN 'L3_BETA' THEN 20 ELSE 50 END)
);
INSERT INTO supporter_private.gradual_campaign(singleton) VALUES(true);
CREATE TABLE supporter_private.gradual_interest (
 owner_id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
 campaign_id uuid NOT NULL REFERENCES supporter_private.gradual_campaign(id),
 sequence bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
 state text NOT NULL DEFAULT 'waiting' CHECK(state IN('waiting','slot_granted','paying','payment_verifying','benefits_active','benefits_ended','issue','withdrawn','declined')),
 joined_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 last_action_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 slot_token uuid, slot_expires_at timestamptz,
 intent_id text UNIQUE REFERENCES supporter_private.pazo_paypal_live_checkout_intents(intent_id),
 provider_started boolean NOT NULL DEFAULT false,
 revision bigint NOT NULL DEFAULT 0,
 feedback text CHECK(feedback IN('ok','issue','skipped')),
 feedback_component text CHECK(feedback_component IN('badge','profile_posts','access','management')),
 feedback_at timestamptz,
 CHECK((slot_token IS NULL)=(slot_expires_at IS NULL))
);
CREATE INDEX gradual_fifo ON supporter_private.gradual_interest(sequence) WHERE state='waiting';
CREATE TABLE supporter_private.gradual_invitation (
 owner_id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
 campaign_id uuid NOT NULL REFERENCES supporter_private.gradual_campaign(id),
 expires_at timestamptz NOT NULL,
 state text NOT NULL DEFAULT 'invited' CHECK(state IN('invited','interested','declined','expired'))
);
