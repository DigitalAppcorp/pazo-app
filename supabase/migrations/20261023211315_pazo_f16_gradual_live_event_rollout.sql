CREATE FUNCTION supporter_private.gradual_legacy_open() RETURNS bigint LANGUAGE sql STABLE SECURITY DEFINER SET search_path='' AS $$
 SELECT count(*) FROM supporter_private.pazo_paypal_live_checkout_intents i WHERE i.closed_at IS NULL
 AND NOT EXISTS(SELECT 1 FROM supporter_private.gradual_interest q WHERE q.intent_id=i.intent_id)
 AND NOT (supporter_private.gradual_verified(i.owner_id) AND EXISTS(SELECT 1 FROM supporter_private.pazo_paypal_live_paid_periods p WHERE p.intent_id=i.intent_id AND p.service_start<=statement_timestamp() AND p.service_end>statement_timestamp()));
$$;
CREATE FUNCTION supporter_private.gradual_notice(p_owner uuid,p_kind text,p_state text) RETURNS void LANGUAGE sql SECURITY DEFINER SET search_path='' AS $$
 INSERT INTO supporter_private.gradual_outbox(campaign_id,owner_id,kind,desired_state)
 SELECT id,p_owner,p_kind,p_state FROM supporter_private.gradual_campaign WHERE singleton
 ON CONFLICT(campaign_id,owner_id,kind) DO UPDATE SET desired_state=excluded.desired_state,
 version=gradual_outbox.version+1,next_attempt_at=clock_timestamp()
 WHERE gradual_outbox.desired_state<>excluded.desired_state AND gradual_outbox.kind='invitation';
$$;
CREATE FUNCTION supporter_private.gradual_enqueue() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
BEGIN
 IF TG_TABLE_NAME='pazo_paypal_live_event_inbox' THEN
  IF NEW.linked_intent_id IS NOT NULL THEN INSERT INTO supporter_private.gradual_event(intent_id) VALUES(NEW.linked_intent_id);END IF;
 ELSE INSERT INTO supporter_private.gradual_event(intent_id) VALUES(NEW.intent_id);END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER gradual_paid_event AFTER INSERT OR UPDATE ON supporter_private.pazo_paypal_live_paid_periods FOR EACH ROW EXECUTE FUNCTION supporter_private.gradual_enqueue();
CREATE TRIGGER gradual_intent_event AFTER INSERT OR UPDATE ON supporter_private.pazo_paypal_live_checkout_intents FOR EACH ROW EXECUTE FUNCTION supporter_private.gradual_enqueue();
CREATE TRIGGER gradual_inbox_event AFTER UPDATE ON supporter_private.pazo_paypal_live_event_inbox FOR EACH ROW WHEN(NEW.processing_state IS DISTINCT FROM OLD.processing_state) EXECUTE FUNCTION supporter_private.gradual_enqueue();
