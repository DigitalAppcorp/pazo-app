CREATE FUNCTION supporter_private.gradual_eligible(p_owner uuid) RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path='' AS $$
 SELECT EXISTS(SELECT 1 FROM auth.users u JOIN public.profiles p ON p.id=u.id
 WHERE u.id=p_owner AND u.email_confirmed_at IS NOT NULL AND u.is_anonymous IS DISTINCT FROM true
 AND p.onboarding_completed IS TRUE AND (u.banned_until IS NULL OR u.banned_until<statement_timestamp()))
 AND NOT EXISTS(SELECT 1 FROM admin_private.pazo_live_release_control WHERE singleton AND canary_owner=p_owner)
 AND NOT EXISTS(SELECT 1 FROM supporter_private.f16_sandbox_qa_owners WHERE owner_id=p_owner)
 AND NOT EXISTS(SELECT 1 FROM account_requests_private.deletion_requests WHERE subject_user_id=p_owner AND status IN('requested','processing'));
$$;
CREATE FUNCTION supporter_private.gradual_health() RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path='' AS $$
 SELECT admin_private.pazo_live_artifact_ready()
 AND EXISTS(SELECT 1 FROM admin_private.pazo_live_release_control r JOIN admin_private.pazo_paypal_new_checkout_switch s ON s.singleton AND s.revision=r.revision WHERE r.singleton AND r.mode IN('canary','limited','public') AND s.environment='live' AND s.live_enabled AND NOT s.kill_switch AND s.active_generation=r.merchant_generation)
 AND EXISTS(SELECT 1 FROM supporter_private.gradual_campaign WHERE singleton AND hosted_gate_verified
  AND webhook_ok_at BETWEEN statement_timestamp()-interval '5 minutes' AND statement_timestamp())
 AND EXISTS(SELECT 1 FROM supporter_private.pazo_paypal_live_worker_control WHERE singleton AND enabled AND processing_enabled
  AND expected_build='pazo_live_worker_v2' AND last_heartbeat_at BETWEEN statement_timestamp()-interval '5 minutes' AND statement_timestamp())
 AND NOT EXISTS(SELECT 1 FROM supporter_private.gradual_incident WHERE resolved_at IS NULL)
 AND NOT EXISTS(SELECT 1 FROM supporter_private.pazo_paypal_live_event_inbox WHERE processing_state='held')
 AND EXISTS(SELECT 1 FROM supporter_private.pazo_live_offer_versions WHERE price_minor=299 AND currency='USD');
$$;
CREATE FUNCTION supporter_private.gradual_verified(p_owner uuid) RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path='' AS $$
 SELECT COALESCE((supporter_private.pazo_live_project_paid_periods(p_owner,statement_timestamp())->>'active')::boolean,false)
 AND EXISTS(SELECT 1 FROM supporter_private.pazo_paypal_live_paid_periods p
 JOIN supporter_private.pazo_paypal_live_checkout_intents i ON i.intent_id=p.intent_id AND i.merchant_generation=p.merchant_generation
 JOIN supporter_private.pazo_paypal_live_event_inbox e ON e.merchant_generation=p.merchant_generation AND e.provider_event_id=p.provider_event_id
 JOIN supporter_private.pazo_paypal_live_signed_receipts r ON r.merchant_generation=p.merchant_generation AND r.provider_event_id=p.provider_event_id
 JOIN admin_private.pazo_paypal_merchant_generations g ON g.generation=p.merchant_generation AND g.environment='live' AND g.plan_id=i.plan_id AND g.webhook_id=r.signature_webhook_id
 WHERE i.owner_id=p_owner AND p.verified_event_type='PAYMENT.SALE.COMPLETED' AND p.amount_minor=299 AND p.currency='USD'
 AND i.source_environment='live' AND i.state='bound' AND r.proof_source='paypal_live_postback_success'
 AND r.subscription_id=i.provider_subscription_id AND r.subject_id=p.sale_id AND e.processing_state='processed'
 AND r.event_type='PAYMENT.SALE.COMPLETED' AND e.event_type='PAYMENT.SALE.COMPLETED' AND p.service_start<=statement_timestamp() AND p.service_end>statement_timestamp()
 AND NOT EXISTS(SELECT 1 FROM supporter_private.pazo_paypal_live_period_holds h WHERE h.sale_id=p.sale_id AND h.released_at IS NULL));
$$;
