 attempts integer NOT NULL DEFAULT 0, next_attempt_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 PRIMARY KEY(campaign_id,owner_id,kind),CHECK((lease_token IS NULL)=(lease_expires_at IS NULL))
