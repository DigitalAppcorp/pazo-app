test('F16 blocks premature offer until BOTH independent server-owned checks settle',()=>{
 assert.match(page,/membership\.kind==='checking'/)
 assert.match(page,/qaV2Screen&&membership\.kind==='inactive'&&qaV2AccountState==='checking'/)
 assert.match(page,/membership\.kind==='unavailable'/)
 assert.match(page,/qaV2Screen&&membership\.kind==='inactive'&&qaV2AccountState==='unavailable'/)
 assert.ok(page.includes('const preparing=preparationPending||preparationUnavailable'))
 assert.ok(page.includes('hidden={preparing} className="sticky'))
 assert.ok(page.includes('hidden={preparing} className="mx-auto'))
 assert.ok(page.includes('<SupporterPreparingScreen lang={lang}'))
 assert.ok(page.includes('<SandboxV2AccountPanel lang={lang}'),'The QA child must stay mounted while hidden to finish the owner check')
 assert.ok(page.includes('<SandboxCheckoutQaPanel lang={lang} inline'),'First checkout remains behind authority gate')
 assert.ok(page.includes("membership.kind === 'verified'"),'Verified membership keeps existing benefits route')
 assert.ok(page.includes("qaV2AccountState==='none'"),'The offer cannot invent absence from loading')
})

