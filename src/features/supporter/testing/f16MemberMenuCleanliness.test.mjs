import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const pet=readFileSync(new URL('../../../components/views/PetView.tsx',import.meta.url),'utf8')
const home=readFileSync(new URL('../components/SupporterBenefitsHome.tsx',import.meta.url),'utf8')
const qa=readFileSync(new URL('../components/SandboxV2AccountPanel.tsx',import.meta.url),'utf8')
const status=readFileSync(new URL('../useSupporterMembershipStatus.ts',import.meta.url),'utf8')
test('PetView entry looks identical while server determines whether subscription is paid',()=>{
 const begin=pet.indexOf('<button ref={supporterAccountEntryRef}')
 const end=pet.indexOf('</button>',begin)
 assert.ok(begin>=0&&end>begin)
 const menu=pet.slice(begin,end)
 assert.ok(menu.includes('Amigo de PAZO'))
 assert.ok(menu.includes('Tu membresía y beneficios'))
 assert.ok(!menu.includes('Consultando tu membresía'))
 assert.ok(!menu.includes('Apoya por US$2.99 al mes'))
 assert.ok(!menu.includes("supporterStatus.kind==='checking'"))
 assert.ok(menu.includes("aria-label={supporterStatus.kind==='verified'"))
 assert.ok(menu.includes('<IconPaw size={22}/>'))
 assert.ok(menu.includes('onClick={() => setShowSupporterAccount(true)}'))
})
test('account-wide membership lookup requires only one owner-scoped RPC, never a browser payment flag',()=>{
 assert.ok(status.includes("if(!petId){"))
 assert.ok(status.includes("supabase.rpc('pazo_supporter_my_account_status')"))
 assert.ok(status.includes("(!value.active&&value.milestone!==0)"))
 assert.ok(status.includes("SUPPORTER_PAYMENT_VERIFIED_EVENT"))
 assert.ok(!status.includes('localStorage'))
 assert.ok(!status.includes('sessionStorage'))
})
test('normal members see payment verification, renewal cancellation and refresh, not Sandbox QA',()=>{
 assert.ok(home.includes('<SandboxV2AccountPanel lang={lang} consumer/>'))
 assert.ok(home.includes('showQaDiagnostics&&<details'))
 assert.ok(home.includes("get('supporter_debug')==='1'"))
 assert.ok(home.includes("['localhost','127.0.0.1']"))
 const compact=qa.slice(qa.indexOf('if(consumer)return'),qa.indexOf("const button='",qa.indexOf('if(consumer)return')))
 assert.ok(compact.includes('Membresía verificada hasta'))
 assert.ok(compact.includes('Actualizar estado'))
 assert.ok(compact.includes('Cancelar futuras renovaciones'))
 assert.ok(compact.includes('onClick={()=>void cancel()}'))
 assert.ok(!compact.includes('Descargar aceptación V2'))
 assert.ok(!compact.includes('Verificar pago real Sandbox'))
 assert.ok(!compact.includes('Consultar PayPal Sandbox'))
 assert.ok(!compact.includes('Ver ejemplos de insignias'))
 assert.ok(!compact.includes('checkMerchantInventory()'))
})
