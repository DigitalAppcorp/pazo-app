test('only admin-authenticated RPC returns aggregate projection',()=>{
 const ix=sql.indexOf('CREATE FUNCTION public.pazo_admin_marketing_summary')
 const piece=sql.slice(ix,sql.indexOf('REVOKE ALL ON FUNCTION public.pazo_admin_marketing_summary',ix))
 assert.ok(ix>=0)
 assert.ok(piece.includes('auth.uid() IS NULL OR NOT public.pazo_is_admin()'))
 assert.ok(piece.includes('p_days NOT IN(7,30,90)'))
 assert.ok(piece.includes('marketing_private.daily_campaign_summary()'))
 assert.ok(piece.includes("'daily'"))
 assert.ok(!piece.includes("'owner_id'"))
 assert.ok(!piece.includes("'email'"))
 assert.ok(!piece.includes("'ip'"))
 assert.ok(sql.includes('GRANT EXECUTE ON FUNCTION public.pazo_admin_marketing_summary(integer)\n TO authenticated'))
 assert.ok(!sql.includes('GRANT EXECUTE ON FUNCTION public.pazo_admin_marketing_summary(integer)\n TO anon'))
 assert.ok(pg.includes('Ordinary account accessed marketing report'))
 assert.ok(pg.includes('Marketing admin response contains identity'))
})
